#!/usr/bin/env python3
"""
Multi-camera ros2bag to LeRobot dataset conversion.
Operates as a ROS 2 Node, loading config from the recorded_bags_meta.yaml
generated by the sobits_vla_rosbag_collection package.
"""
import os
import cv2
import yaml
import numpy as np
import torch
from pathlib import Path

import rclpy
from rclpy.node import Node

from rosbags.highlevel import AnyReader
from rosbags.image import message_to_cvimage
from lerobot.datasets.lerobot_dataset import LeRobotDataset
from sobits_vla_rosbag_conversion.tf_buffer import OfflineTFTree, mat_to_pose6d


class RosbagConversionNode(Node):
    def __init__(self):
        super().__init__('rosbag_conversion_node')

        self.declare_parameter('rosbag_directory', '')
        self.declare_parameter('dataset_name', 'MyDataset')
        self.declare_parameter('output_directory', '')
        self.declare_parameter('push_to_hub', False)
        self.declare_parameter('hub_private', False)
        self.declare_parameter('skip_static_threshold', 0.0)
        self.declare_parameter('ee_pose.enabled', False)
        self.declare_parameter('ee_pose.target_frame', 'base_link')
        self.declare_parameter('ee_pose.source_frame', 'hand_palm_link')
        self.declare_parameter('cameras.skip', False)
        self.declare_parameter('cameras.primary', 'head_camera')
        self.declare_parameter('cameras.names', [''])
        self.declare_parameter('cameras.compressed', [False])

        self.rosbag_directory = self.get_parameter('rosbag_directory').get_parameter_value().string_value
        self.dataset_name = self.get_parameter('dataset_name').get_parameter_value().string_value
        output_dir = self.get_parameter('output_directory').get_parameter_value().string_value
        self.output_directory = Path(output_dir) if output_dir else None
        self.push_to_hub = self.get_parameter('push_to_hub').get_parameter_value().bool_value
        self.hub_private = self.get_parameter('hub_private').get_parameter_value().bool_value
        self.skip_static_threshold = self.get_parameter('skip_static_threshold').get_parameter_value().double_value
        self.ee_pose_enabled = self.get_parameter('ee_pose.enabled').get_parameter_value().bool_value
        self.ee_pose_target = self.get_parameter('ee_pose.target_frame').get_parameter_value().string_value
        self.ee_pose_source = self.get_parameter('ee_pose.source_frame').get_parameter_value().string_value
        self.skip_cameras = self.get_parameter('cameras.skip').get_parameter_value().bool_value
        self.primary_camera = self.get_parameter('cameras.primary').get_parameter_value().string_value
        raw_names = self.get_parameter('cameras.names').get_parameter_value().string_array_value
        self.cameras_names = [n for n in raw_names if n]  # filter empty placeholder
        self.cameras_compressed = list(self.get_parameter('cameras.compressed').get_parameter_value().bool_array_value)

        # Configuration attributes (populated from YAML)
        self.camera_topics = {}
        self.topic_to_cam = {}
        self.joint_states_topic = ""
        self.cmd_vel_topic = ""
        self.odom_topic = ""
        self.sync_threshold = 0.1
        self.has_mobile_base = False
        self.has_cmd_vel_y = False
        self.has_cmd_vel_z = False
        self.action_features = []
        self.all_subtasks_list = []
        self.subtask_label_to_idx = {}
        self.has_subtasks = False

        # Conversion tracking
        self.episode_stats = []
        self.skipped_bags = []  # [(bag_path, [missing_topics])]

        # One-shot timer to start conversion after the node is ready
        self.timer = self.create_timer(1.0, self.timer_callback)

    def timer_callback(self):
        """One-shot timer callback to trigger the conversion."""
        self.timer.cancel()
        try:
            self.convert()
        except Exception as e:
            self.get_logger().error(f"Conversion failed: {e}")
            import traceback
            self.get_logger().error(traceback.format_exc())
        finally:
            self.get_logger().info("Shutting down node...")
            raise SystemExit

    # Compare two morphology blocks for consistency
    def _morphologies_match(self, ref_morph: dict, other_morph: dict) -> bool:
        """Return True if the two morphology dicts are functionally equivalent."""
        for key in ["type", "has_mobile_base", "has_cmd_vel_y", "joint_states_topic"]:
            if ref_morph.get(key) != other_morph.get(key):
                return False
        ref_parts = ref_morph.get("parts", [])
        other_parts = other_morph.get("parts", [])
        if ref_parts != other_parts:
            return False
        for part in ref_parts:
            rp = ref_morph.get(part, {})
            op = other_morph.get(part, {})
            if rp.get("is_actionable") != op.get("is_actionable"):
                return False
            if rp.get("joint_names", []) != op.get("joint_names", []):
                return False
        return True

    # Episode extraction
    def _extract_episode_data(self, bag_folder, subtasks_map):
        """
        Iterate over the bag and return a list of (timestamp, frame) tuples.
        Uses connection-level topic filter (O1) and cached topic_to_cam (O2).
        """
        frames = []
        skipped_static = 0
        skipped_tf = 0
        skipped_img_decode = 0
        images = {cam_name: None for cam_name in self.camera_topics.keys()}
        image_times = {cam_name: 0.0 for cam_name in self.camera_topics.keys()}
        latest_joint_state = None
        latest_joint_velocity = None
        latest_joint_time = 0.0
        latest_cmd_vel = [0.0] * len(self.base_keys) if self.has_mobile_base else None
        latest_cmd_vel_time = 0.0
        # Per-joint commanded positions and timestamps (from JointTrajectory messages)
        commanded_joints = {}       # {joint_name: position}
        commanded_joints_time = {}  # {joint_name: timestamp}

        # EE pose tracking
        tf_tree = OfflineTFTree() if self.ee_pose_enabled else None
        prev_ee_pose = None

        # Compute wanted topic set and filter connections
        wanted = set(self.camera_topics.values()) | {self.joint_states_topic}
        wanted |= self.part_command_topics  # JointTrajectory topics (required for action)
        if self.has_mobile_base and self.cmd_vel_topic:
            wanted.add(self.cmd_vel_topic)
        if self.ee_pose_enabled:
            wanted |= {"/tf", "/tf_static"}

        last_frame_time = 0.0  # timestamp of the last assembled frame (for freshness)

        sync_deltas = []

        with AnyReader([Path(bag_folder)]) as reader:
            # Pre-validate topics — log each missing topic with its purpose
            available = {c.topic for c in reader.connections}
            missing = wanted - available
            if missing:
                self.get_logger().error(f"Bag '{bag_folder}' is missing {len(missing)} required topic(s). Skipping episode.")
                for m in sorted(missing):
                    if m == self.joint_states_topic:
                        reason = "joint state observation"
                    elif m in self.part_command_topics:
                        reason = "joint command (action)"
                    elif m == self.cmd_vel_topic:
                        reason = "base velocity command (action.base)"
                    elif m in self.topic_to_cam:
                        reason = f"camera image ({self.topic_to_cam[m]})"
                    elif m in ("/tf", "/tf_static"):
                        reason = "TF transforms (ee_pose)"
                    else:
                        reason = "unknown"
                    self.get_logger().error(f"  missing: {m}  ({reason})")
                self.skipped_bags.append({
                    "bag": bag_folder,
                    "reason": "missing_topics",
                    "missing": {m: reason for m in sorted(missing) for reason in [
                        "joint_state" if m == self.joint_states_topic else
                        "joint_command" if m in self.part_command_topics else
                        "base_velocity" if m == self.cmd_vel_topic else
                        f"camera:{self.topic_to_cam[m]}" if m in self.topic_to_cam else
                        "tf" if m in ("/tf", "/tf_static") else "unknown"
                    ]},
                })
                return None

            # Filter at connection level
            connections = [c for c in reader.connections if c.topic in wanted]

            for connection, timestamp, rawdata in reader.messages(connections=connections):
                topic = connection.topic
                t_bag = timestamp * 1e-9

                if topic == self.joint_states_topic:
                    msg = reader.deserialize(rawdata, connection.msgtype)
                    joint_pos = dict(zip(msg.name, msg.position))
                    joint_vel = dict(zip(msg.name, msg.velocity)) if msg.velocity else {}
                    t_sec = msg.header.stamp.sec + msg.header.stamp.nanosec * 1e-9
                    latest_joint_state = [joint_pos.get(feat, 0.0) for feat in self.action_features]
                    latest_joint_velocity = [joint_vel.get(feat, 0.0) for feat in self.action_features]
                    latest_joint_time = t_sec

                elif tf_tree is not None and topic in ("/tf", "/tf_static"):
                    msg = reader.deserialize(rawdata, connection.msgtype)
                    tf_tree.ingest(msg, is_static=(topic == "/tf_static"))

                elif topic in self.part_command_topics:
                    msg = reader.deserialize(rawdata, connection.msgtype)
                    # JointTrajectory messages carry commanded positions
                    if hasattr(msg, 'joint_names') and hasattr(msg, 'points') and msg.points:
                        target_point = msg.points[-1]  # final waypoint = target
                        t_cmd = msg.header.stamp.sec + msg.header.stamp.nanosec * 1e-9 if hasattr(msg, 'header') and msg.header.stamp.sec > 0 else t_bag
                        for jn, pos in zip(msg.joint_names, target_point.positions):
                            commanded_joints[jn] = pos
                            commanded_joints_time[jn] = t_cmd

                elif topic == self.cmd_vel_topic and self.has_mobile_base:
                    msg = reader.deserialize(rawdata, connection.msgtype)
                    t_sec = msg.header.stamp.sec + msg.header.stamp.nanosec * 1e-9 if hasattr(msg, 'header') else t_bag
                    if self.has_cmd_vel_y and self.has_cmd_vel_z:
                        latest_cmd_vel = [msg.linear.x, msg.linear.y, msg.linear.z, msg.angular.z]
                    elif self.has_cmd_vel_y:
                        latest_cmd_vel = [msg.linear.x, msg.linear.y, msg.angular.z]
                    elif self.has_cmd_vel_z:
                        latest_cmd_vel = [msg.linear.x, msg.linear.z, msg.angular.z]
                    else:
                        latest_cmd_vel = [msg.linear.x, msg.angular.z]
                    latest_cmd_vel_time = t_sec

                elif topic in self.topic_to_cam:
                    cam_name = self.topic_to_cam[topic]
                    msg = reader.deserialize(rawdata, connection.msgtype)
                    try:
                        if hasattr(msg, 'format'):
                            # CompressedImage: decode JPEG/PNG bytes via OpenCV
                            img = cv2.imdecode(np.frombuffer(msg.data, dtype=np.uint8), cv2.IMREAD_COLOR)
                            if img is None:
                                skipped_img_decode += 1
                                continue
                            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
                        else:
                            # Raw Image: use rosbags conversion
                            img = message_to_cvimage(msg)
                            if len(img.shape) == 3 and img.shape[2] == 3:
                                if msg.encoding in ['bgr8', 'bgra8']:
                                    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
                    except Exception:
                        skipped_img_decode += 1
                        continue
                    t_sec = msg.header.stamp.sec + msg.header.stamp.nanosec * 1e-9
                    images[cam_name] = img
                    image_times[cam_name] = t_sec

                    # Snapshot trigger: primary camera
                    if cam_name == self.primary_camera and latest_joint_state is not None:
                        if any(v is None for v in images.values()):
                            continue
                        if self.has_mobile_base and latest_cmd_vel is None:
                            continue

                        # Sync checks
                        img_times = list(image_times.values())
                        max_camera_diff = max(img_times) - min(img_times)
                        joint_diff = abs(image_times[self.primary_camera] - latest_joint_time)
                        cmd_vel_diff = abs(image_times[self.primary_camera] - latest_cmd_vel_time) if self.has_mobile_base else 0.0
                        max_sync = max(max_camera_diff, joint_diff, cmd_vel_diff)

                        if max_sync > self.sync_threshold:
                            self.get_logger().warn(
                                f"Sync threshold exceeded: cam_diff={max_camera_diff:.3f}s, "
                                f"joint_diff={joint_diff:.3f}s, cmd_vel_diff={cmd_vel_diff:.3f}s"
                            )
                        sync_deltas.append(max_sync)

                        # Skip static frames: skip if no joint velocity exceeds threshold
                        if self.skip_static_threshold > 0.0 and latest_joint_velocity is not None:
                            if not np.any(np.abs(latest_joint_velocity) > self.skip_static_threshold):
                                skipped_static += 1
                                continue

                        # State: measured joint positions only (no cmd_vel)
                        state = latest_joint_state
                        # Action: commanded joint positions, fall back to measured if not yet received
                        action = [
                            commanded_joints.get(feat, latest_joint_state[i])
                            for i, feat in enumerate(self.action_features)
                        ]
                        frame = {
                            "action": torch.tensor(action, dtype=torch.float32),
                            "observation.state": torch.tensor(state, dtype=torch.float32),
                        }

                        # Freshness masks
                        joint_dim = len(self.action_features)
                        state_fresh = latest_joint_time > last_frame_time
                        frame["observation.state.is_fresh"] = torch.full(
                            (joint_dim,), state_fresh, dtype=torch.bool
                        )

                        # Per-joint action freshness based on individual command timestamps
                        action_freshness = [
                            commanded_joints_time.get(feat, 0.0) > last_frame_time
                            for feat in self.action_features
                        ]
                        frame["action.is_fresh"] = torch.tensor(action_freshness, dtype=torch.bool)

                        # Delta action: commanded - measured per joint
                        delta = [action[i] - state[i] for i in range(joint_dim)]
                        frame["action.delta"] = torch.tensor(delta, dtype=torch.float32)
                        # Delta freshness requires both command and state to be fresh
                        delta_freshness = [
                            action_freshness[i] and state_fresh
                            for i in range(joint_dim)
                        ]
                        frame["action.delta.is_fresh"] = torch.tensor(delta_freshness, dtype=torch.bool)

                        # Base velocity action (separate feature, inherently delta)
                        if self.has_mobile_base:
                            frame["action.base"] = torch.tensor(latest_cmd_vel, dtype=torch.float32)
                            cmd_vel_fresh = latest_cmd_vel_time > last_frame_time
                            frame["action.base.is_fresh"] = torch.full(
                                (len(self.base_keys),), cmd_vel_fresh, dtype=torch.bool
                            )

                        # End-effector pose via TF chain
                        if tf_tree is not None:
                            stamp_ns = int(t_sec * 1e9)
                            ee_mat = tf_tree.resolve(
                                self.ee_pose_target, self.ee_pose_source, stamp_ns
                            )
                            if ee_mat is None:
                                skipped_tf += 1
                                if skipped_tf <= 5:
                                    self.get_logger().warn(
                                        f"TF lookup failed: '{self.ee_pose_source}' → '{self.ee_pose_target}' "
                                        f"at t={t_sec:.3f}s. Skipping frame."
                                    )
                                continue
                            ee_abs = mat_to_pose6d(ee_mat)
                            if prev_ee_pose is not None:
                                for ax in range(3, 6):
                                    diff = ee_abs[ax] - prev_ee_pose[ax]
                                    if diff > np.pi:
                                        ee_abs[ax] -= 2 * np.pi
                                    elif diff < -np.pi:
                                        ee_abs[ax] += 2 * np.pi
                                ee_rel = ee_abs - prev_ee_pose
                            else:
                                ee_rel = np.zeros(6, dtype=np.float32)
                            frame["observation.ee_pose"] = torch.from_numpy(ee_abs.copy())
                            frame["observation.ee_pose.delta"] = torch.from_numpy(ee_rel)
                            prev_ee_pose = ee_abs.copy()

                        if not self.skip_cameras:
                            for c_name in self.camera_topics.keys():
                                img_arr = np.ascontiguousarray(images[c_name].transpose(2, 0, 1))
                                frame[f"observation.images.{c_name}"] = torch.from_numpy(img_arr)
                                cam_fresh = image_times[c_name] > last_frame_time
                                frame[f"observation.images.{c_name}.is_fresh"] = torch.full(
                                    (3, 1, 1), cam_fresh, dtype=torch.bool
                                )

                        # Subtask annotation
                        if self.all_subtasks_list and subtasks_map:
                            current_subtask_idx = 0
                            for _, st_info in (subtasks_map.items() if isinstance(subtasks_map, dict) else {}):
                                start_t = st_info.get("start_timestamp", -1.0) if isinstance(st_info, dict) else -1.0
                                end_t = st_info.get("end_timestamp", float('inf')) if isinstance(st_info, dict) else float('inf')
                                if end_t == 0.0:
                                    end_t = float('inf')
                                if start_t <= t_sec <= end_t:
                                    label = st_info.get("label", "") if isinstance(st_info, dict) else ""
                                    current_subtask_idx = self.subtask_label_to_idx.get(label, 0)
                                    break
                            frame["subtask_index"] = torch.tensor([current_subtask_idx], dtype=torch.int64)

                        frames.append((t_sec, frame))
                        last_frame_time = t_sec
                        images[self.primary_camera] = None

        if skipped_tf > 5:
            self.get_logger().warn(f"TF lookup failed {skipped_tf} times total (suppressed after 5).")
        if skipped_img_decode > 0:
            self.get_logger().warn(f"Image decode failed {skipped_img_decode} times.")

        return frames, sync_deltas, skipped_static, skipped_tf, skipped_img_decode

    # Main conversion
    def convert(self):
        self.get_logger().info("Starting dataset conversion...")
        self.get_logger().info(f"Target dataset name: {self.dataset_name}")
        self.get_logger().info(f"Reading from rosbags root: {self.rosbag_directory}")

        # Discover metadata files
        meta_files = []
        for root, _, files in os.walk(self.rosbag_directory):
            for file in files:
                if file == "recorded_bags_meta.yaml":
                    meta_files.append(os.path.join(root, file))

        if not meta_files:
            self.get_logger().error(f"No recorded_bags_meta.yaml found in {self.rosbag_directory}")
            return

        self.get_logger().info(f"Found {len(meta_files)} metadata file(s).")

        all_tasks = []
        all_users = []
        robot_ref_name = None
        robot_ref_version = None
        ref_morphology = None
        robot_info = {}

        for idx, meta_file in enumerate(meta_files):
            with open(meta_file, "r") as f:
                meta = yaml.safe_load(f)

            robot_info = meta.get("robot_info", {})
            r_name = robot_info.get("name")
            r_vers = robot_info.get("version")
            morphology = robot_info.get("morphology", {})

            if idx == 0:
                robot_ref_name = r_name
                robot_ref_version = r_vers
                ref_morphology = morphology

                convert_info = meta.get("convert_info", {})
                fps = convert_info.get("fps", 10)
                self.sync_threshold = convert_info.get("sync_threshold", 0.1)

                try:
                    self.joint_states_topic = morphology.get("joint_states_topic", "/joint_states")
                    parts = morphology.get("parts", [])

                    self.action_features = []  # joint names (excludes mobile base)
                    self.part_command_topics = set()  # topics carrying joint commands
                    for part in parts:
                        part_info = morphology.get(part, {})
                        if part_info.get("is_actionable", False):
                            if part in ["mobile_base", "legs"]:
                                self.has_mobile_base = True
                                self.has_cmd_vel_y = part_info.get("has_cmd_vel_y", False)
                                self.has_cmd_vel_z = part_info.get("has_cmd_vel_z", False)
                                self.cmd_vel_topic = part_info.get("cmd_vel_topic", "/cmd_vel")
                                self.odom_topic = part_info.get("odom_topic", "")
                            else:
                                self.action_features.extend(part_info.get("joint_names", []))
                                cmd_topic = part_info.get("command_topic", "")
                                if cmd_topic:
                                    self.part_command_topics.add(cmd_topic)

                    if not self.action_features and not self.has_mobile_base:
                        self.get_logger().error("No actionable joints and no active mobile base found. Aborting.")
                        return
                except Exception as e:
                    self.get_logger().error(f"Error extracting morphology features: {e}")
                    return
            else:
                # Morphology comparison
                if r_name != robot_ref_name or r_vers != robot_ref_version:
                    self.get_logger().error(
                        f"Robot identity mismatch! Expected {robot_ref_name} v{robot_ref_version}, "
                        f"got {r_name} v{r_vers} in {meta_file}"
                    )
                    return
                if not self._morphologies_match(ref_morphology, morphology):
                    self.get_logger().error(
                        f"Morphology mismatch in {meta_file}. All sessions must share identical "
                        "robot morphology (parts, is_actionable flags, joint_names). Aborting."
                    )
                    return

            u_info = meta.get("user_info")
            if u_info and u_info not in all_users:
                all_users.append(u_info)

            for t_name, t_info in meta.get("recorded_bags", {}).get("tasks", {}).items():
                t_info["_meta_source_dir"] = os.path.dirname(meta_file)
                all_tasks.append((t_name, t_info))

        # Build flat per-camera maps from all sensor types
        sensors = robot_info.get("sensors", {})
        sensor_types = sensors.get("types", [])
        all_cam_raw = {}         # name -> raw topic
        all_cam_compressed = {}  # name -> compressed topic
        all_cam_props = {}       # name -> properties dict (width, height)

        for stype in sensor_types:
            sdata = sensors.get(stype, {})
            names = sdata.get("names", [])
            topics = sdata.get("topics", [])
            compressed_topics = sdata.get("compressed_topics", [])
            props = sdata.get("properties", {})
            for i, name in enumerate(names):
                if i < len(topics):
                    all_cam_raw[name] = topics[i]
                if i < len(compressed_topics) and compressed_topics[i]:
                    all_cam_compressed[name] = compressed_topics[i]
                all_cam_props[name] = props.get(name, {})

        if not all_cam_raw:
            self.get_logger().error("No usable camera sensor type found in metadata. Exiting.")
            return

        # Apply camera selection: use config list or fall back to all cameras
        selected_names = self.cameras_names if self.cameras_names else list(all_cam_raw.keys())
        selected_compressed = list(self.cameras_compressed)
        # Pad compressed flags with False if shorter than names
        if len(selected_compressed) < len(selected_names):
            selected_compressed += [False] * (len(selected_names) - len(selected_compressed))

        self.camera_topics = {}
        for name, use_compressed in zip(selected_names, selected_compressed):
            if name not in all_cam_raw:
                self.get_logger().error(f"Camera '{name}' not found in metadata sensors. Aborting.")
                return
            if use_compressed:
                topic = all_cam_compressed.get(name, "")
                if not topic:
                    self.get_logger().warn(f"Camera '{name}': no compressed topic in metadata, falling back to raw.")
                    topic = all_cam_raw[name]
            else:
                topic = all_cam_raw[name]
            self.camera_topics[name] = topic

        # O2: build cached reverse map once
        self.topic_to_cam = {v: k for k, v in self.camera_topics.items()}

        if self.primary_camera not in self.camera_topics:
            fallback = list(self.camera_topics.keys())[0]
            self.get_logger().warn(f"Primary camera '{self.primary_camera}' not in selected cameras. Falling back to '{fallback}'.")
            self.primary_camera = fallback

        # Subtask index
        all_subtasks_set = set()
        for _, task_info in all_tasks:
            for _, ep_meta in task_info.get("episodes", {}).items():
                subtasks = ep_meta.get("subtasks", {})
                if isinstance(subtasks, dict):
                    for _, st_info in subtasks.items():
                        if isinstance(st_info, dict) and "label" in st_info:
                            all_subtasks_set.add(st_info["label"])

        self.all_subtasks_list = sorted(list(all_subtasks_set))
        if self.all_subtasks_list:
            self.all_subtasks_list.insert(0, "No Subtask")
        self.subtask_label_to_idx = {label: i for i, label in enumerate(self.all_subtasks_list)}
        self.has_subtasks = len(self.all_subtasks_list) > 0

        # Feature schema
        self.base_keys = []
        if self.has_mobile_base:
            if self.has_cmd_vel_y and self.has_cmd_vel_z:
                self.base_keys = ["base_x", "base_y", "base_z", "base_theta"]
            elif self.has_cmd_vel_y:
                self.base_keys = ["base_x", "base_y", "base_theta"]
            elif self.has_cmd_vel_z:
                self.base_keys = ["base_x", "base_z", "base_theta"]
            else:
                self.base_keys = ["base_x", "base_theta"]

        joint_dim = len(self.action_features)
        base_dim = len(self.base_keys)

        features = {
            # Joint action: commanded positions (absolute)
            "action": {"dtype": "float32", "shape": (joint_dim,), "names": self.action_features},
            "action.is_fresh": {"dtype": "bool", "shape": (joint_dim,), "names": None},
            # Joint action delta: commanded - measured
            "action.delta": {"dtype": "float32", "shape": (joint_dim,), "names": self.action_features},
            "action.delta.is_fresh": {"dtype": "bool", "shape": (joint_dim,), "names": None},
            # Joint state: measured positions from /joint_states
            "observation.state": {"dtype": "float32", "shape": (joint_dim,), "names": self.action_features},
            "observation.state.is_fresh": {"dtype": "bool", "shape": (joint_dim,), "names": None},
        }
        # Base velocity action (separate — already delta, different units from joint positions)
        if self.has_mobile_base:
            features["action.base"] = {"dtype": "float32", "shape": (base_dim,), "names": self.base_keys}
            features["action.base.is_fresh"] = {"dtype": "bool", "shape": (base_dim,), "names": None}
        if self.ee_pose_enabled:
            ee_names = ["x", "y", "z", "roll", "pitch", "yaw"]
            features["observation.ee_pose"] = {
                "dtype": "float32", "shape": (6,), "names": ee_names,
            }
            features["observation.ee_pose.delta"] = {
                "dtype": "float32", "shape": (6,), "names": ee_names,
            }

        if self.has_subtasks:
            features["subtask_index"] = {"dtype": "int64", "shape": (1,), "names": ["subtask_index"]}

        if not self.skip_cameras:
            for cam_name in self.camera_topics.keys():
                props = all_cam_props.get(cam_name, {})
                w = props.get("width", 640)
                h = props.get("height", 480)
                features[f"observation.images.{cam_name}"] = {
                    "dtype": "video",
                    "shape": (3, h, w),
                    "names": ["channels", "height", "width"],
                }
                features[f"observation.images.{cam_name}.is_fresh"] = {
                    "dtype": "bool",
                    "shape": (3, 1, 1),
                    "names": None,
                }

        # Create dataset
        dataset = LeRobotDataset.create(
            repo_id=self.dataset_name,
            fps=fps,
            features=features,
            root=self.output_directory,
            video_backend="auto",
            streaming_encoding=True,
        )

        if self.has_subtasks:
            import pandas as pd
            dataset.meta.subtasks = pd.DataFrame({"subtask": self.all_subtasks_list})

        if hasattr(dataset, "info"):
            dataset.info["robot_info"] = robot_info
            if all_users:
                dataset.info["user_info"] = all_users if len(all_users) > 1 else all_users[0]

        # Count total episodes for progress logging
        total_episodes = 0
        for _, task_info in all_tasks:
            meta_src = task_info.get("_meta_source_dir", self.rosbag_directory)
            bag_group = task_info.get("bag_path", task_info.get("bag_dir", ""))
            group_dir = os.path.join(meta_src, bag_group) if not bag_group.startswith("/") else bag_group
            if os.path.isdir(group_dir):
                total_episodes += sum(
                    1 for ep in os.listdir(group_dir)
                    if os.path.isdir(os.path.join(group_dir, ep))
                    and any(f.endswith(".db3") or f.endswith(".mcap")
                            for f in os.listdir(os.path.join(group_dir, ep)))
                )

        first_episode_done = False
        current_episode_num = 0

        # Conversion loop
        for _, (task_name, task_info) in enumerate(all_tasks):
            meta_src = task_info.get("_meta_source_dir", self.rosbag_directory)
            bag_group = task_info.get("bag_path", task_info.get("bag_dir", task_name))
            group_dir = os.path.join(meta_src, bag_group) if not bag_group.startswith("/") else bag_group

            if not os.path.isdir(group_dir):
                group_dir = os.path.join(meta_src, task_name)
                if not os.path.isdir(group_dir):
                    self.get_logger().warn(f"Directory not found: {group_dir}")
                    continue

            episodes_dict = task_info.get("episodes", {})
            instruction = task_info.get("label", task_info.get("instructions", task_name))

            for ep in sorted(os.listdir(group_dir)):
                ep_path = os.path.join(group_dir, ep)
                if not os.path.isdir(ep_path):
                    continue
                bag_files = [f for f in os.listdir(ep_path) if f.endswith(".db3") or f.endswith(".mcap")]
                if not bag_files:
                    continue

                bagfile = os.path.join(ep_path, bag_files[0])
                current_episode_num += 1

                # progress bar
                self.get_logger().info(f"[{current_episode_num}/{total_episodes}] Processing: {bagfile}")

                ep_meta = episodes_dict.get(ep, {})
                subtasks = ep_meta.get("subtasks", {})

                try:
                    result = self._extract_episode_data(os.path.dirname(bagfile), subtasks_map=subtasks)
                except Exception as e:
                    self.get_logger().error(f"Failed to read bag {bagfile}: {e}")
                    self.skipped_bags.append({
                        "bag": os.path.dirname(bagfile),
                        "reason": "read_error",
                        "error": str(e),
                    })
                    continue

                if result is None:
                    # Missing required topics — already logged and tracked in skipped_bags
                    continue
                frames, sync_deltas, ep_skipped_static, ep_skipped_tf, ep_skipped_img = result

                if not frames:
                    self.get_logger().warn(
                        f"No frames extracted from {bagfile} "
                        f"(skipped_static={ep_skipped_static}, skipped_tf={ep_skipped_tf}, "
                        f"skipped_img_decode={ep_skipped_img})"
                    )
                    self.skipped_bags.append({
                        "bag": os.path.dirname(bagfile),
                        "reason": "no_frames",
                        "skipped_static": ep_skipped_static,
                        "skipped_tf": ep_skipped_tf,
                        "skipped_img_decode": ep_skipped_img,
                    })
                    continue

                # FPS validation on first episode
                # TODO: check onyl first episode?
                if not first_episode_done and len(frames) > 1:
                    first_episode_done = True
                    duration = frames[-1][0] - frames[0][0]
                    if duration > 0:
                        actual_fps = len(frames) / duration
                        if actual_fps < fps * 0.8:
                            self.get_logger().warn(
                                f"Actual frame rate ({actual_fps:.1f} fps) is significantly lower than "
                                f"configured dataset fps ({fps}). Consider reducing fps in record_settings."
                            )

                for _, frame in frames:
                    dataset.add_frame(frame)

                dataset.save_episode(task=instruction)

                # Accumulate episode stats
                ep_stat = {
                    "bag": os.path.basename(ep_path),
                    "task": instruction,
                    "frames": len(frames),
                    "skipped_static": ep_skipped_static,
                    "skipped_tf": ep_skipped_tf,
                    "skipped_img_decode": ep_skipped_img,
                }
                if sync_deltas:
                    ep_stat["sync_avg_ms"] = round(float(np.mean(sync_deltas) * 1000), 2)
                    ep_stat["sync_max_ms"] = round(float(np.max(sync_deltas) * 1000), 2)
                    ep_stat["sync_min_ms"] = round(float(np.min(sync_deltas) * 1000), 2)
                self.episode_stats.append(ep_stat)
                self.get_logger().info(f"  → Saved {len(frames)} frames.")

        if not self.episode_stats:
            self.get_logger().error("No episodes were successfully converted. Dataset is empty.")
        else:
            dataset.finalize()
            self.get_logger().info(f"Dataset saved to: {dataset.root}")
            self.get_logger().info("Dataset creation completed!")

        if self.push_to_hub and self.episode_stats:
            self.get_logger().info(f"Pushing dataset to HuggingFace Hub as '{self.dataset_name}'...")
            dataset.push_to_hub(private=self.hub_private)
            self.get_logger().info("Push to Hub completed!")

        # Write conversion stats to YAML alongside the dataset
        stats_report = {
            "dataset_name": self.dataset_name,
            "rosbag_directory": self.rosbag_directory,
            "fps": fps,
            "sync_threshold": self.sync_threshold,
            "skip_static_threshold": self.skip_static_threshold,
            "ee_pose_enabled": self.ee_pose_enabled,
            "cameras_skip": self.skip_cameras,
            "total_episodes": len(self.episode_stats),
            "total_frames": sum(s["frames"] for s in self.episode_stats),
            "skipped_bags": self.skipped_bags if self.skipped_bags else [],
            "episodes": self.episode_stats,
        }
        stats_path = Path(dataset.root) / "conversion_stats.yaml"
        with open(stats_path, "w") as f:
            yaml.dump(stats_report, f, default_flow_style=False, sort_keys=False)
        self.get_logger().info(f"Conversion stats saved to: {stats_path}")

        # Log summary
        self.get_logger().info(
            f"Summary: {len(self.episode_stats)} episodes, "
            f"{stats_report['total_frames']} frames, "
            f"{len(self.skipped_bags)} skipped bags"
        )


def main(args=None):
    rclpy.init(args=args)
    node = RosbagConversionNode()
    try:
        rclpy.spin(node)
    except (KeyboardInterrupt, SystemExit):
        pass
    finally:
        node.destroy_node()
        rclpy.shutdown()


if __name__ == "__main__":
    main()
